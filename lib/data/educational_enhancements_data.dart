class ExamCountdown {
  final String name;
  final DateTime date;
  final String stage;
  final IconData icon;
  final Color color;

  const ExamCountdown({
    required this.name,
    required this.date,
    required this.stage,
    required this.icon,
    required this.color,
  });

  /// حساب الوقت المتبقي الفعلي حتى الامتحان القادم
  Duration get remaining {
    final now = DateTime.now();
    var target = date;
    // إذا كان تاريخ الامتحان للسنة الحالية قد مضى، يحسب تلقائياً للدورة القادمة
    if (target.isBefore(now)) {
      target = DateTime(target.year + 1, target.month, target.day, target.hour, target.minute);
    }
    return target.difference(now);
  }

  DateTime get nextDate {
    final now = DateTime.now();
    var target = date;
    if (target.isBefore(now)) {
      target = DateTime(target.year + 1, target.month, target.day, target.hour, target.minute);
    }
    return target;
  }
}

